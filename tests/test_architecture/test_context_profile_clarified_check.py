def test_module_and_operations_with_preloaded_dependencies_need_no_ambient_access(monkeypatch):
    source = MODULE.read_text()
    code = compile(source, "pure-clarified-checker", "exec")
    imports = {node.module for node in ast.walk(ast.parse(source)) if isinstance(node, ast.ImportFrom)}
    assert imports == {"__future__", "configs.architecture.bin"}
    assert not any(isinstance(node, ast.Import) for node in ast.walk(ast.parse(source)))
    loaded = {name: __import__(name, fromlist=("context_profile_check", "context_profile_clarifications") if name == "configs.architecture.bin" else ()) for name in imports}
    good_p, good_r = profile(), record()
    bad_p = profile()
    bad_p["constraints"][0]["source"]["answer"] = "not the recorded answer"
    open_r = record()
    open_r["events"] = []
    open_p = bind(original_only_profile(), open_r)
    invalid_r = {**record(), "extra": True}
    modules_before = set(sys.modules)
    before = copy.deepcopy((good_p, good_r, bad_p, open_p, open_r, invalid_r, SCHEMA))
    namespace = {"__name__": "guarded_clarified", "__file__": "must-not-resolve"}

    def deny(*args, **kwargs):
        raise AssertionError("checker attempted ambient access")

    def only_preloaded(name, globals=None, locals=None, fromlist=(), level=0):
        assert name in loaded and level == 0, f"unexpected import: {name}"
        if name == "configs.architecture.bin":
            assert fromlist in (("context_profile_check",), ("context_profile_clarifications",))
        return loaded[name]

    class NoEnvironment:
        __getitem__ = __iter__ = __contains__ = get = deny

    with monkeypatch.context() as patch:
        patch.setattr(builtins, "open", deny)
        patch.setattr(io, "open", deny)
        for name in ("open", "stat", "listdir", "scandir", "getenv", "getcwd", "urandom", "system"):
            patch.setattr(os, name, deny)
        patch.setattr(os, "environ", NoEnvironment())
        for name in ("open", "read_text", "read_bytes", "resolve", "exists", "stat"):
            patch.setattr(Path, name, deny)
        for name in ("time", "monotonic", "perf_counter", "time_ns", "sleep"):
            patch.setattr(time, name, deny)
        for name in ("socket", "create_connection", "getaddrinfo"):
            patch.setattr(socket, name, deny)
        patch.setattr(subprocess, "Popen", deny)
        patch.setattr(subprocess, "run", deny)
        patch.setattr(sqlite3, "connect", deny)
        # Guard setup itself imports inspect. Install the identical import guard
        # last, before executing any module code, as learned in #308.
        patch.setattr(builtins, "__import__", only_preloaded)
        exec(code, namespace)
        validator = v2.Validator(SCHEMA)
        outputs = [namespace["check_clarified_profile"](p, BRIEF, r, validator) for p, r in
                   ((good_p, good_r), (bad_p, good_r), (open_p, open_r), (good_p, invalid_r))]
    assert [out["references_ok"] for out in outputs] == [True, False, True, False]
    assert [e["reason"] for e in outputs[1]["errors"]] == ["clarification_answer_mismatch"]
    assert outputs[2]["unresolved_questions"][0]["state"] == "unanswered"
    assert outputs[3]["errors"][0]["reason"] == "invalid_record"
    assert all(out["meaning_status"] == "NOT_EVALUATED" for out in outputs)
    assert (good_p, good_r, bad_p, open_p, open_r, invalid_r, SCHEMA) == before
    assert not {name for name in set(sys.modules) - modules_before if name.startswith("temper_ai")}
