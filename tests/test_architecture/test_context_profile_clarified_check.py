def bind(p, r, brief=BRIEF):
    # Construct variant INPUTS using the #308 source contract, not checker output.
    mapping = c.compose_supplement(r, brief)["source_mapping"]
    p["clarification_source"] = {key: mapping[key] for key in ("source_id", "record_sha256")}
    p["brief_sha256"] = hashlib.sha256(brief.encode()).hexdigest()
    # Only bindings are updated. Never infer an answer or supporting events here.
    def visit(node):
        if isinstance(node, dict):
            if node.get("kind") == "clarification":
                node["source_id"] = mapping["source_id"]
            for value in node.values():
                visit(value)
        elif isinstance(node, list):
            for value in node:
                visit(value)
    visit(p)
    return p


def put(p, path, value):
    node = p
    for key in path[:-1]:
        node = node[key]
    node[path[-1]] = value
    return p


def run(p=None, r=None, brief=BRIEF, validator=VALIDATOR):
    report = checked.check_clarified_profile(profile() if p is None else p, brief, record() if r is None else r, validator)
    assert set(report) == {"references_ok", "errors", "counts", "unresolved_questions", "meaning_status"}
    assert report["meaning_status"] == "NOT_EVALUATED"
    assert report["references_ok"] == (report["errors"] == [])
    return report


def passes(p=None, r=None, brief=BRIEF):
    report = run(p, r, brief)
    assert report["errors"] == []
    return report


def fails(p, reason, path=None, r=None, brief=BRIEF):
    report = run(p, r, brief)
    assert report["references_ok"] is False
    assert any(e["reason"] == reason and (path is None or e["path"] == path) for e in report["errors"]), report["errors"]
    return report


