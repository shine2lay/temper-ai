@pytest.mark.parametrize("mode,expected", [("deferred", "deferred"), ("unknown", "unknown"), ("conflict", "conflicting"),
                                           ("reopen", "reopened"), ("model", "unanswered"), ("model-with-human", "answered")])
def test_only_current_answered_human_state_can_support_a_reference(mode, expected):
    r = record()
    if mode in ("deferred", "unknown"):
        r["events"][0]["disposition"] = mode
    elif mode == "conflict":
        r["events"].append(event(event_id="e-conflict", answer="no"))
    elif mode == "reopen":
        r["events"].append({"event_id": "e-reopen", "question_id": Q1, "kind": "reopen",
                            "actor": {"kind": "human", "ref": "actor:alice"}, "source": {"kind": "human_response", "ref": "message:reopen"},
                            "reason": "The requirement changed."})
    else:
        generated = event(event_id="e-model", answer="different model suggestion")
        generated["actor"]["kind"] = "model"
        generated["source"]["kind"] = "model_output"
        r["events"] = ([r["events"][1]] if mode == "model" else r["events"]) + [generated]
    p = bind(profile(), r)
    if expected == "answered":
        assert passes(p, r)["unresolved_questions"] == []
        p["constraints"][0]["source"]["event_ids"] = ["e-1", "e-model"]
        fails(p, "clarification_events_mismatch", r=r)
    else:
        states = fails(p, "clarification_unresolved", r=r)["unresolved_questions"]
        assert len(states) == 1 and states[0]["question_id"] == Q1 and states[0]["state"] == expected
        assert states[0]["answer"] is None
        if mode == "model":
            assert states[0]["model_event_ids"] == ["e-model"]
        # Removing the unsupported reference, not resolving the question, permits
        # independent work. Unresolved prose is not promoted to evidence.
        p["constraints"][0]["source"] = assumption()
        assert passes(p, r)["unresolved_questions"] == states


